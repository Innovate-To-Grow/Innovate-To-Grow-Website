"""The inbound classifier: each automated class from its strong signals, the order they are tried in, and the rule
that anything uncertain is human (content-only signs are hints, never a class). Pure: no database."""

from django.test import SimpleTestCase

from apps.core.services.email.inbound import AUTOMATED, HUMAN, LABELS, Evidence, auth_summary, classify
from apps.core.services.email.inbound.classify import spam_confidence_level

SITE = "i2g@ucmerced.edu"
OWN = frozenset({SITE})


def evidence(headers=None, **values) -> Evidence:
    values.setdefault("from_address", "pat@example.org")
    values.setdefault("subject", "Question about the showcase")
    return Evidence(headers={key.lower(): [value] for key, value in (headers or {}).items()}, **values)


def verdict_of(headers=None, **values):
    return classify(evidence(headers, **values), own_addresses=OWN)


class HumanTests(SimpleTestCase):
    def test_a_plain_message_is_human_with_no_hints(self):
        verdict = verdict_of(text_head="Hello, when does it start?")

        self.assertEqual((verdict.classification, verdict.automated, verdict.hints), (HUMAN, False, ()))

    def test_content_only_signs_are_hints_never_a_class(self):
        cases = {
            "possible_auto_reply": {"subject": "Out of office next week", "text_head": "I will be on vacation."},
            "possible_left_org": {"text_head": "I have a new email address: pat@new.example"},
            "possible_receipt": {"subject": "Read: chapter two"},
            "possible_system_mail": {"text_head": "This is an automated message from our portal."},
        }
        for hint, values in cases.items():
            with self.subTest(hint):
                verdict = verdict_of(**values)
                self.assertEqual(verdict.classification, HUMAN)
                self.assertIn(hint, verdict.hints)

    def test_weak_headers_are_hints_only(self):
        verdict = verdict_of({"X-Auto-Response-Suppress": "All", "Return-Path": "<>"})

        self.assertEqual(verdict.classification, HUMAN)
        self.assertEqual(set(verdict.hints), {"auto_response_suppress", "null_return_path"})

    def test_auto_submitted_no_is_a_person(self):
        self.assertEqual(verdict_of({"Auto-Submitted": "no"}).classification, HUMAN)


class OwnMailTests(SimpleTestCase):
    def test_the_sites_address_proven_by_exchange_or_dkim_is_own_mail(self):
        internal = verdict_of({"X-MS-Exchange-Organization-AuthAs": "Internal"}, from_address=SITE)
        signed = verdict_of(
            {
                "Authentication-Results": "spf=pass smtp.mailfrom=ucmerced.edu; dkim=pass (signature) header.d=ucmerced.edu"
            },
            from_address=SITE,
        )

        self.assertEqual((internal.classification, signed.classification), ("own", "own"))
        self.assertTrue(internal.automated)

    def test_a_forged_site_address_is_not_own_mail_and_is_flagged(self):
        unproven = verdict_of({}, from_address=SITE)
        other_domain = verdict_of({"Authentication-Results": "dkim=pass header.d=attacker.example"}, from_address=SITE)

        for verdict in (unproven, other_domain):
            self.assertEqual(verdict.classification, HUMAN)
            self.assertIn("claims_own_address", verdict.hints)


class AutomatedClassTests(SimpleTestCase):
    def test_bounce_reports(self):
        report = verdict_of(content_type="multipart/report", report_type="delivery-status")
        failed = verdict_of({"X-Failed-Recipients": "nobody@example.org"})
        daemon = verdict_of(from_address="mailer-daemon@mx.example.org")
        exchange = verdict_of(from_address="microsoftexchange329e71ec88ae4615bbc36ab6ce41109e@ucmerced.edu")

        for verdict in (report, failed, daemon, exchange):
            self.assertEqual(verdict.classification, "bounce")

    def test_receipts(self):
        read = verdict_of(content_type="multipart/report", report_type="disposition-notification")
        delivered = verdict_of(
            subject="Delivered: Hello", content_type="multipart/report", report_type="delivery-status"
        )
        read_by_subject = verdict_of(subject="Read: Hello", content_type="multipart/report", report_type="")

        self.assertEqual((read.classification, read.subtype), ("receipt", "read"))
        self.assertEqual((delivered.classification, delivered.subtype), ("receipt", "delivery"))
        self.assertEqual(read_by_subject.classification, "receipt")

    def test_automatic_replies_by_header(self):
        for headers in (
            {"Auto-Submitted": "auto-replied"},
            {"X-Autoreply": "yes"},
            {"X-Autorespond": "yes"},
            {"X-Autogenerated": "Reply"},
            {"Precedence": "auto_reply"},
        ):
            with self.subTest(headers):
                verdict = verdict_of(headers, text_head="Thanks for your message.")
                self.assertEqual((verdict.classification, verdict.subtype), ("auto_reply", "other"))

    def test_automatic_reply_subjects_in_several_languages(self):
        for subject in (
            "Automatic reply: Innovate to Grow",
            "Auto-Reply: Innovate to Grow",
            "Out of Office: Innovate to Grow",
            "Abwesenheitsnotiz: Innovate to Grow",
            "Réponse automatique : Innovate to Grow",
            "Respuesta automática: Innovate to Grow",
            "Risposta automatica: Innovate to Grow",
            "自动回复: Innovate to Grow",
        ):
            with self.subTest(subject):
                self.assertEqual(verdict_of(subject=subject).classification, "auto_reply")

    def test_vacation_and_left_the_organisation_subtypes(self):
        vacation = verdict_of({"Auto-Submitted": "auto-replied"}, text_head="I am on vacation until Monday.")
        left = verdict_of({"Auto-Submitted": "auto-replied"}, text_head="Jordan has left the company.")
        new_address = verdict_of(subject="Automatic reply: Hi", text_head="Please use my new email address.")

        self.assertEqual((vacation.classification, vacation.subtype), ("auto_reply", "vacation"))
        self.assertEqual(left.classification, "left_org")
        self.assertEqual(new_address.classification, "left_org")
        self.assertTrue(left.automated)

    def test_auto_generated_mail_that_is_no_reply_is_system_mail(self):
        verdict = verdict_of({"Auto-Submitted": "auto-generated"}, subject="Your report is ready")

        self.assertEqual((verdict.classification, verdict.subtype), ("system", "auto_generated"))

    def test_calendar_replies_and_quarantine_notices_are_system_mail(self):
        calendar = verdict_of(subject="Accepted: Judges' briefing", has_calendar=True)
        not_calendar = verdict_of(subject="Accepted: your proposal?")
        quarantine = verdict_of(from_address="quarantine@gateway.example")

        self.assertEqual((calendar.classification, calendar.subtype), ("system", "calendar"))
        self.assertEqual(not_calendar.classification, HUMAN)
        self.assertEqual((quarantine.classification, quarantine.subtype), ("system", "quarantine"))

    def test_list_and_bulk_mail(self):
        listed = verdict_of({"List-Id": "<news.example>"})
        esp = verdict_of({"X-SG-EID": "abc"})
        precedence = verdict_of({"Precedence": "bulk"})
        noreply = verdict_of(from_address="no-reply@service.example")

        self.assertEqual((listed.classification, listed.subtype), ("bulk", "list"))
        self.assertEqual((esp.classification, esp.subtype), ("bulk", "newsletter"))
        self.assertEqual(precedence.classification, "bulk")
        self.assertEqual((noreply.classification, noreply.subtype), ("bulk", "noreply"))

    def test_spam_by_exchange_verdicts(self):
        scl = verdict_of({"X-MS-Exchange-Organization-SCL": "6"})
        report = verdict_of({"X-Forefront-Antispam-Report": "CIP:192.0.2.1;CTRY:US;SCL:5;SRV:;IPV:NLI;SFV:NSPM"})
        filtered = verdict_of({"X-Forefront-Antispam-Report": "CIP:192.0.2.1;SCL:1;SFV:SPM;"})
        below = verdict_of({"X-MS-Exchange-Organization-SCL": "4"})
        trusted = verdict_of({"X-MS-Exchange-Organization-SCL": "-1"})

        self.assertEqual((scl.classification, report.classification, filtered.classification), ("spam",) * 3)
        self.assertEqual((below.classification, trusted.classification), (HUMAN, HUMAN))
        self.assertEqual(
            classify(evidence({"X-MS-Exchange-Organization-SCL": "4"}), scl_threshold=4).classification, "spam"
        )

    def test_the_first_matching_class_wins(self):
        # An NDR also carries Auto-Submitted and may come from a list: it is a bounce report first.
        verdict = verdict_of(
            {"Auto-Submitted": "auto-replied", "List-Id": "<x>"},
            content_type="multipart/report",
            report_type="delivery-status",
        )
        self.assertEqual(verdict.classification, "bounce")
        # A vacation reply sent through a list is an automatic reply before it is list mail.
        self.assertEqual(
            verdict_of({"Auto-Submitted": "auto-replied", "Precedence": "bulk"}).classification, "auto_reply"
        )

    def test_every_automated_class_has_a_label(self):
        self.assertTrue(AUTOMATED <= set(LABELS))
        self.assertNotIn(HUMAN, AUTOMATED)


class AuthenticationSummaryTests(SimpleTestCase):
    def test_reads_the_first_result_of_each_method_and_the_scl(self):
        headers = {
            "authentication-results": ["spf=pass smtp.mailfrom=x; dkim=fail header.d=x; dmarc=fail; compauth=fail"],
            "x-ms-exchange-organization-scl": ["1"],
        }

        self.assertEqual(
            auth_summary(headers), {"spf": "pass", "dkim": "fail", "dmarc": "fail", "compauth": "fail", "scl": 1}
        )
        self.assertEqual(auth_summary({}), {})

    def test_the_highest_scl_is_used_and_garbage_is_ignored(self):
        headers = {
            "x-ms-exchange-organization-scl": ["abc"],
            "x-forefront-antispam-report": ["SCL:2;", "CIP:1;SCL:7"],
        }

        self.assertEqual(spam_confidence_level(headers), 7)
        self.assertIsNone(spam_confidence_level({"x-ms-exchange-organization-scl": ["n/a"]}))
